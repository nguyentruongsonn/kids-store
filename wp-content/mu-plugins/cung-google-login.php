<?php
/**
 * Plugin Name: Cưng Google Login Integration
 * Description: Connects the Nextend Google provider to WooCommerce and Blocksy account forms.
 * Version: 1.0.0
 */
defined('ABSPATH') || exit;

/** Missing credentials or a disabled provider never produce a broken login button. */
function cung_google_login_provider() {
    if (!class_exists('NextendSocialLogin')) { return false; }
    $provider = NextendSocialLogin::getProviderByProviderID('google');
    if (!$provider || !$provider->isEnabled() || !$provider->isTested()) { return false; }
    if (!$provider->settings->get('client_id') || !$provider->settings->get('client_secret')) { return false; }
    return $provider;
}

function cung_google_login_render_button() {
    $provider = cung_google_login_provider();
    if (is_user_logged_in() || !$provider) { return; }
    $redirect = function_exists('wc_get_page_permalink') ? wc_get_page_permalink('myaccount') : home_url('/');
    echo '<div class="cung-google-login">';
    echo '<div class="cung-google-login-divider" aria-hidden="true"><span>hoặc</span></div>';
    // HTML is generated by the OAuth provider, including its state and popup handling.
    echo NextendSocialLogin::renderButtonsWithContainer('default', [$provider], $redirect, false, 'left'); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
    echo '</div>';
}
// Blocksy's account modal also fires this WooCommerce hook.
add_action('woocommerce_login_form_end', 'cung_google_login_render_button', 20);

add_action('wp_enqueue_scripts', function () {
    if (is_user_logged_in() || !cung_google_login_provider()) { return; }
    $path = WPMU_PLUGIN_DIR . '/cung-google-login.css';
    wp_enqueue_style('cung-google-login', plugins_url('cung-google-login.css', __FILE__), [], (string) filemtime($path));
});

// Follow the store's own account creation policy for Google registrations.
add_filter('nsl_is_register_allowed', function ($allowed, $provider) {
    if (!$provider || $provider->getId() !== 'google' || !class_exists('WooCommerce')) { return $allowed; }
    return 'yes' === get_option('woocommerce_enable_myaccount_registration')
        || 'yes' === get_option('woocommerce_enable_signup_and_login_from_checkout');
}, 20, 2);

// Apply a customer role only to accounts created through Google, never existing users.
add_action('nsl_google_register_new_user', function ($user_id) {
    if (class_exists('WooCommerce') && get_role('customer')) {
        $user = get_userdata($user_id);
        if ($user) { $user->set_role('customer'); }
    }
}, 10, 1);

add_action('admin_menu', function () {
    add_options_page('Đăng nhập Google', 'Đăng nhập Google', 'manage_options', 'cung-google-login', 'cung_google_login_settings_page');
});

function cung_google_login_settings_page() {
    if (!current_user_can('manage_options')) { return; }
    $installed = class_exists('NextendSocialLogin');
    $provider = $installed && isset(NextendSocialLogin::$providers['google']) ? NextendSocialLogin::$providers['google'] : false;
    $ready = (bool) cung_google_login_provider();
    $callback = $provider ? $provider->getBaseRedirectUriForAppCreation() : '';
    ?>
    <div class="wrap">
      <h1>Đăng nhập Google</h1>
      <p><?php echo esc_html($ready ? 'Google đã được cấu hình và bật.' : 'Đã chuẩn bị tích hợp. Đang chờ Client ID, Client Secret và xác minh kết nối Google.'); ?></p>
      <table class="widefat striped" style="max-width:900px"><tbody>
        <tr><th>OAuth provider</th><td><?php echo esc_html($installed ? 'Nextend Social Login ' . NextendSocialLogin::$version : 'Chưa kích hoạt Nextend Social Login'); ?></td></tr>
        <tr><th>Nơi hiển thị</th><td>Trang Tài khoản, form đăng nhập WooCommerce và popup tài khoản Blocksy.</td></tr>
        <tr><th>Authorized redirect URI</th><td><code><?php echo esc_html($callback); ?></code></td></tr>
        <tr><th>Trạng thái nút</th><td><?php echo esc_html($ready ? 'Hiển thị cho khách chưa đăng nhập.' : 'Ẩn cho đến khi provider được xác minh và bật.'); ?></td></tr>
      </tbody></table>
      <p><a class="button button-primary" href="<?php echo esc_url(admin_url('options-general.php?page=nextend-social-login&view=provider-google&subview=settings')); ?>">Nhập thông tin Google</a></p>
      <p>Lưu Client ID và Client Secret trong cấu hình Google của Nextend, chạy Verify Settings, sau đó Enable Google.</p>
      <p>Khi đổi từ localhost sang tên miền thật, cập nhật Authorized redirect URI trong Google Cloud bằng URL mới hiển thị ở đây.</p>
    </div>
    <?php
}
